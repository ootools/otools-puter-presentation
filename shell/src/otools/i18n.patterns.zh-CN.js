/**
 * 模式表：带插值的文案按形状认。
 * ------------------------------------------------------------------
 * 上游有大量文案是模板串拼出来的（`Open ${name}`、`${n} slides`），
 * 永远不可能成为词典的键，只能按形状认。
 *
 * 每条都是**锚定正则**（`^…$`，不带 `g`）。替换函数返回**空串**表示
 * 「这条不适用」，让文案保持英文并出现在缺口报告里——宁可半句英文，
 * 也别拼出「重置 Reset all」这种半成品。
 *
 * 第二参数 `t` 是翻译函数：捕获组若是界面文案（控件名、条目名、单位）
 * 就用 `t(组)` 递归再翻一次；若是用户数据（文件名、幻灯片标题）就原样
 * 保留，不要对整条做二次翻译。
 *
 * ⚠️ **顺序即优先级**，从具体到宽泛：先单位读数，再快捷键后缀，
 * 然后各类具体句式，最后才是 `Add/Open/New + 任意` 这类通用式。
 * ⚠️ `i18n-report.mjs` 不统计模式表，它只按词典算覆盖率——
 * 本文件的效果要在运行时看，别拿报告的百分比验收。
 */
export const patterns = [
  // ── 单位与数值读数（必须早于「快捷键后缀」，否则 `(seconds)` 会被误判）──
  [/^(.+) pt$/, (m) => `${m[1]} 磅`],
  [/^(.+) mm$/, (m) => `${m[1]} 毫米`],
  [/^(.+) seconds$/, (m) => `${m[1]} 秒`],
  [/^Temperature: (.+) K$/, (m) => `色温：${m[1]} K`],
  [/^(Saturation|Transparency): (.+)%$/, (m, t) => `${t(m[1]) || m[1]}：${m[2]}%`],
  [/^Glow: (.+), Accent (.+)$/, (m) => `发光：${m[1]}，强调文字颜色 ${m[2]}`],
  [/^(.+), Accent (.+)$/, (m) => `${m[1]}，强调文字颜色 ${m[2]}`],

  // ── 带快捷键后缀的菜单项（`保存 (⌘+S)`）─────────────────────────
  // 捕获组里必须含至少一个非字母符号（⌘⇧⌥⌃ 或 + - = [ ] /）才算快捷键，
  // 否则像 `(seconds)`、`(of 24)` 这类会被误收。
  [/^(.+) \(([^()]*[⌘⌥⌃⇧+\-=\[\]\/][^()]*)\)$/, (m, t) => `${t(m[1]) || m[1]} (${m[2]})`],

  // ── 幻灯片 / 页 ────────────────────────────────────────────────
  [/^Show slide (.+)$/, (m) => `显示幻灯片 ${m[1]}`],
  [/^Copy slide (.+)$/, (m) => `复制幻灯片 ${m[1]}`],
  [/^Read slide (.+)$/, (m) => `朗读幻灯片 ${m[1]}`],
  [/^Move slide (.+)$/, (m) => `移动幻灯片 ${m[1]}`],
  [/^Write speaker notes for slide (.+)$/, (m) => `为幻灯片 ${m[1]} 编写演讲者备注`],
  [/^Add a (.+) table to slide (.+)$/, (m) => `向幻灯片 ${m[2]} 添加 ${m[1]} 表格`],
  [/^Edit table cells on slide (.+)$/, (m) => `编辑幻灯片 ${m[1]} 上的表格单元格`],
  [/^Slide (\d+): (.+)$/, (m) => `幻灯片 ${m[1]}：${m[2]}`],
  [/^Slide (\d+)$/, (m) => `幻灯片 ${m[1]}`],
  [/^Slides of (.+)$/, (m) => `${m[1]} 的幻灯片`],

  // ── 形状 / 条目 / 图片 ─────────────────────────────────────────
  [/^Item (\d+), level (\d+)$/, (m) => `第 ${m[1]} 项，第 ${m[2]} 级`],
  [/^Item (\d+) text$/, (m) => `第 ${m[1]} 项的文本`],
  [/^Picture (\d+)$/, (m) => `图片 ${m[1]}`],
  [/^Caption for picture (\d+)$/, (m) => `图片 ${m[1]} 的题注`],
  [/^Bookmark (\d+)$/, (m) => `书签 ${m[1]}`],
  [/^(Equation|Graphic|Freeform|Style|Pattern) (\d+)$/, (m, t) => `${t(m[1]) || m[1]} ${m[2]}`],
  [/^(\d+) by (\d+) table$/, (m) => `${m[1]} × ${m[2]} 表格`],

  // ── 图表 ───────────────────────────────────────────────────────
  [/^Series (\d+)$/, (m) => `系列 ${m[1]}`],
  [/^Name of series (\d+)$/, (m) => `系列 ${m[1]} 的名称`],
  [/^Chart type for (.+)$/, (m) => `${m[1]} 的图表类型`],
  [/^Secondary axis for (.+)$/, (m) => `${m[1]} 的次坐标轴`],
  [/^Shades of accent (\d+)$/, (m) => `强调文字颜色 ${m[1]} 的变体`],
  [/^Stop (\d+) of (\d+),? at (.+)%$/, (m) => `第 ${m[1]} 个色标（共 ${m[2]} 个），位于 ${m[3]}%`],

  // ── 通用动作 ───────────────────────────────────────────────────
  [/^(Duplicate|Delete|Rename|Reset|Increase|Decrease|Add|Open|New) (.+)$/, (m, t) => {
    const verb = { Duplicate: '复制', Delete: '删除', Rename: '重命名', Reset: '重置', Increase: '增大', Decrease: '减小', Add: '添加', Open: '打开', New: '新建' }[m[1]];
    return `${verb}${t(m[2]) || m[2]}`;
  }],
  [/^More (.+)$/, (m, t) => `更多 ${t(m[1]) || m[1]}`],
  [/^(Previous|Next) row of (.+)$/, (m, t) => `${t(m[1]) || m[1]}行（${t(m[2]) || m[2]}）`],
  [/^Go to (.+)$/, (m, t) => `转到 ${t(m[1]) || m[1]}`],
  [/^Tile (.+)$/, (m, t) => `平铺 ${t(m[1]) || m[1]}`],

  // ── 各类「…的选项 / 列表 / 效果 / 纹理」─────────────────────────
  [/^(.+) options$/, (m, t) => `${t(m[1]) || m[1]} 选项`],
  [/^(.+) list$/, (m, t) => `${t(m[1]) || m[1]} 列表`],
  [/^(.+) texture$/, (m, t) => `${t(m[1]) || m[1]} 纹理`],
  [/^(.+) effect$/, (m, t) => `${t(m[1]) || m[1]} 效果`],
  [/^(.+) arrow (type|size)$/, (m, t) => `${t(m[1]) || m[1]} ${m[2] === 'type' ? '箭头类型' : '箭头大小'}`],
  [/^(.+) bevel( width| height)?$/, (m) => `${m[1]} 斜面${m[2] === ' width' ? '宽度' : m[2] === ' height' ? '高度' : ''}`],
  [/^Offset (.+)$/, (m, t) => `${t(m[1]) || m[1]}偏移`],

  // ── 效果与动画 ─────────────────────────────────────────────────
  [/^Play the effects of (.+)$/, (m) => `播放 ${m[1]} 的效果`],
  [/^Options for (.+) on (.+)$/, (m, t) => `${m[2]} 上 ${t(m[1]) || m[1]} 的选项`],
  [/^End of the motion path of (.+)\. Drag or use the arrow keys to move it\.$/, (m) => `${m[1]} 的运动路径终点。拖动或用方向键移动它。`],
  [/^Start (.+)$/, (m, t) => `起点 ${t(m[1]) || m[1]}`],
  [/^(.+) applied$/, (m, t) => `已应用 ${t(m[1]) || m[1]}`],

  // ── 主题与母版 ─────────────────────────────────────────────────
  [/^New presentation in the (.+) theme$/, (m) => `在 ${m[1]} 主题中新建演示文稿`],
  [/^Apply the (.+) palette$/, (m) => `应用 ${m[1]} 调色板`],
  [/^(.+) slide master$/, (m) => `${m[1]} 幻灯片母版`],

  // ── 表格与形状定位 ─────────────────────────────────────────────
  [/^Edit cell, row (\d+), column (\d+)$/, (m) => `编辑单元格，第 ${m[1]} 行，第 ${m[2]} 列`],
  [/^(.+)\. Select to edit$/, (m, t) => `${t(m[1]) || m[1]}。选择以编辑`],
  [/^(.+)\. Right-click to apply to selected slides\.$/, (m) => `${m[1]}。右键单击可应用到所选的幻灯片。`],
  [/^Draw the chosen shape of the graphic as another shape\. (.+)$/, (m, t) => `把图形的所选形状绘制为另一个形状。${t(m[1]) || m[1]}`],
  [/^Options for section (.+)$/, (m) => `节 ${m[1]} 的选项`],
  [/^Clear the tab stop at (.+) inches$/, (m) => `清除 ${m[1]} 英寸处的制表位`],

  // ── 搜索 / 替换 / 删除确认（引号内是用户输入，保留）──────────────
  [/^Search for “(.+)”$/, (m) => `搜索“${m[1]}”`],
  [/^No commands match “(.+)”$/, (m) => `没有匹配“${m[1]}”的命令`],
  [/^Replace “(.+)” with “(.+)”$/, (m) => `将“${m[1]}”替换为“${m[2]}”`],
  [/^Delete “(.+)”\?$/, (m) => `删除“${m[1]}”？`],
  [/^Save “(.+)” to Puter before closing\?$/, (m) => `关闭前将“${m[1]}”保存到 Puter？`],
  [/^(\d+) replies$/, (m) => `${m[1]} 条回复`],
];
